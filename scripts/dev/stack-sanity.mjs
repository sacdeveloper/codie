import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";
const info = JSON.parse(readFileSync("tests/.artifacts/e2e-stack.json", "utf8"));
const sb = createClient(info.supabaseUrl, info.anonKey, { auth: { persistSession: false } });
const { data, error } = await sb.auth.signInWithPassword({ email: info.users.staffA.email, password: info.users.staffA.password });
console.log("signin", error?.message ?? "ok", data.user?.id);
console.log("profile", (await sb.from("profiles").select("role, organisation_id, is_active").eq("id", data.user.id).single()).data);
const ins = await sb.from("reports").insert({ organisation_id: info.organisations.A, template_version: 1 }).select("id, serial_number").single();
console.log("insert", ins.error?.message ?? ins.data);
const up = await sb.storage.from("passport-documents").upload(`${info.organisations.A}/${ins.data.id}/passport/x.pdf`, new TextEncoder().encode("%PDF-1.4 test"), { contentType: "application/pdf" });
console.log("upload", up.error?.message ?? "ok");
const bad = await sb.storage.from("passport-documents").upload(`${info.organisations.B}/x/passport/x.pdf`, new TextEncoder().encode("%PDF-1.4"), { contentType: "application/pdf" });
console.log("cross-org upload", bad.error?.message ?? "UNEXPECTED OK");
const signed = await sb.storage.from("passport-documents").createSignedUrl(`${info.organisations.A}/${ins.data.id}/passport/x.pdf`, 60);
console.log("signed", signed.error?.message ?? (await (await fetch(signed.data.signedUrl)).text()));
const dl = await sb.storage.from("passport-documents").download(`${info.organisations.A}/${ins.data.id}/passport/x.pdf`);
console.log("download", dl.error?.message ?? (await dl.data.text()));
const anon = createClient(info.supabaseUrl, info.anonKey);
console.log("verify rpc", (await anon.rpc("verify_report", { p_token_hash: "0".repeat(64) })).data);
