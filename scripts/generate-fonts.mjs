// Regenerates src/lib/pdf/fonts.generated.ts from the WOFF2 files in src/lib/pdf/fonts/.
import { readFileSync, writeFileSync } from "node:fs";

const dir = "src/lib/pdf/fonts";
const faces = [
  ["ReportSans", 400, "ReportSans-Regular.woff2"],
  ["ReportSans", 700, "ReportSans-Bold.woff2"],
  ["ReportSerif", 400, "ReportSerif-Regular.woff2"],
  ["ReportSerif", 700, "ReportSerif-Bold.woff2"],
];
const css = faces
  .map(([family, weight, file]) => {
    const b64 = readFileSync(`${dir}/${file}`).toString("base64");
    return `@font-face{font-family:"${family}";font-weight:${weight};font-style:normal;src:url(data:font/woff2;base64,${b64}) format("woff2");}`;
  })
  .join("\n");
writeFileSync(
  "src/lib/pdf/fonts.generated.ts",
  `// GENERATED by scripts/generate-fonts.mjs — do not edit. Fonts: SIL OFL 1.1, see src/lib/pdf/fonts/.\n` +
    `export const EMBEDDED_FONT_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`fonts.generated.ts written (${Math.round(css.length / 1024)} KB)`);
