/**
 * Generates SQL files that can be pasted into the Supabase dashboard SQL editor (no CLI needed):
 *   supabase/setup.sql                   all migrations, in order
 *   supabase/bootstrap-organisation.sql  first organisation + active default template + first admin
 * Run: npm run sql:bundle   (a unit test fails if the committed files are out of date)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_TEMPLATE } from "../src/lib/template/default-template";

const ROOT = join(import.meta.dirname, "..");

export function buildSetupSql(): string {
  const dir = join(ROOT, "supabase/migrations");
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  return [
    "-- GENERATED by `npm run sql:bundle` from supabase/migrations — do not edit by hand.",
    "-- Run once in a NEW Supabase project: Dashboard → SQL Editor → paste → Run.",
    "-- (With the Supabase CLI, `supabase db push` applies the same migrations instead.)",
    "",
    ...files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trim()}\n`),
  ].join("\n");
}

export function buildBootstrapSql(): string {
  const json = (v: unknown) => {
    const s = JSON.stringify(v);
    if (s.includes("$json$")) throw new Error("template JSON contains the dollar-quote tag");
    return `$json$${s}$json$::jsonb`;
  };
  return `-- GENERATED by \`npm run sql:bundle\` — do not edit by hand.
-- Creates the first organisation, activates the default report template and makes an existing user its administrator.
--
-- 1. Run supabase/setup.sql first.
-- 2. Dashboard → Authentication → Users → "Add user": enter the administrator's email and a password
--    and tick "Auto Confirm User".
-- 3. Change the two values below, then paste this whole script into the SQL Editor and run it.

do $do$
declare
  v_org_name    text := 'Example Medical Centre';   -- <-- your medical centre
  v_admin_email text := 'admin@example.com';        -- <-- the user created in step 2
  v_org  uuid;
  v_user uuid;
begin
  select id into v_user from auth.users where lower(email) = lower(v_admin_email);
  if v_user is null then
    raise exception 'No auth user with email %. Create it under Authentication → Users first.', v_admin_email;
  end if;

  insert into public.organisations (name, declaration_name) values (v_org_name, v_org_name) returning id into v_org;

  insert into public.report_templates (organisation_id, name, version, field_configuration, letterhead_configuration, layout_configuration, is_active)
  values (v_org, ${JSON.stringify(DEFAULT_TEMPLATE.name).replace(/"/g, "'")}, 1,
    ${json(DEFAULT_TEMPLATE.fieldConfiguration)},
    ${json(DEFAULT_TEMPLATE.letterheadConfiguration)},
    ${json(DEFAULT_TEMPLATE.layoutConfiguration)},
    true);

  insert into public.profiles (id, email, full_name, role, organisation_id, is_active)
  values (v_user, v_admin_email, 'Organisation Administrator', 'org_admin', v_org, true)
  on conflict (id) do update set role = 'org_admin', organisation_id = v_org, is_active = true;

  raise notice 'Organisation % created; % is its administrator.', v_org, v_admin_email;
end
$do$;
`;
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  writeFileSync(join(ROOT, "supabase/setup.sql"), buildSetupSql());
  writeFileSync(join(ROOT, "supabase/bootstrap-organisation.sql"), buildBootstrapSql());
  console.log("supabase/setup.sql and supabase/bootstrap-organisation.sql written");
}
